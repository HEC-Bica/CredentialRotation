<#
.SYNOPSIS
    Powershell Script to bulk create location folders with BiRS Windows account secrets in secretserver
.DESCRIPTION
    Reads the sheet 'rollout' of rollout_CredentialRotation.xlsx and creates one subfolder per row with
    GenerateSecret = TRUE in folder 1340 (\Customer\Freie\_Locations), named after column 'FolderName'
    ("<Ortschaft>.<Jobnummer>"). In every new subfolder one secret per template is created.
    Passwords are generated by secretserver according to the password requirement of the template. Every password
    is checked against the rules below before its secret is saved; a test password per template is checked before
    anything is created, so the script stops at once if a template's password requirement isn't set up yet.
    Folders that already exist and rows without FolderName are skipped with a warning, as are rows whose 6-digit
    job number already appears in the name of another subfolder of folder 1340 (e.g. an older folder of the site).
    Every row is written to ss_Generate-Secret_<timestamp>.csv (JobNr;FolderName;FolderId;Status;Message) with the
    folder ID for created and already existing folders; nb_Import-CredentialFolderId.ps1 imports it into netbox.
    Requires the PowerShell module ImportExcel (Excel itself is not needed).
#>

[string]$SecretServerUrl = 'https://secretserver.lag.wan/SecretServer'
$SecretServerApi = "$SecretServerUrl/winauthwebservices/api/v1"
[int]$SecretServerFolder = 1340
[string]$ExcelPath = ".\rollout_CredentialRotation.xlsx"
[string]$WorksheetName = 'rollout'
[string]$ResultPath = ".\ss_Generate-Secret_$(Get-Date -Format 'yyyyMMdd_HHmmss').csv"

# Rules for the generated passwords (same as the password requirement of the templates in secretserver):
# exactly this length, at least one upper case letter, lower case letter, digit and special character,
# no other characters than letters A-Z/a-z, digits and these special characters
[int]$PasswordLength = 16
[string]$PasswordSpecialChars = '-_.:+#@'

# Username (also used as secret name) and secret template per secret
$SecretDefinitions = @(
    @{ Username = 'BiCA Admin';      TemplateId = 6084 }   # Windows Account (BiRS - BiCA Admin)
    @{ Username = 'BiCA Remote';     TemplateId = 6085 }   # Windows Account (BiRS - BiCA Remote)
    @{ Username = 'ApplicationUser'; TemplateId = 7122 }   # Windows Account (BiRS - ApplicationUser)
    @{ Username = 'PUB-User';        TemplateId = 6087 }   # Windows Account (BiRS - PUB-User)
    @{ Username = 'WinAutoUser';     TemplateId = 7121 }   # Windows Account (BiRS - WinAutoUser)
)

if (!(Get-Module -ListAvailable -Name ImportExcel)) {Write-Host "PowerShell module ImportExcel not installed (Install-Module ImportExcel) - Aborting Script" -ForegroundColor Red ; exit}
if (!(Test-Path -Path $ExcelPath)) {Write-Host "Excel not found: $ExcelPath - Aborting Script" -ForegroundColor Red ; exit}

$Rows = @(Import-Excel -Path $ExcelPath -WorksheetName $WorksheetName | Where-Object { $_.GenerateSecret -eq $true })

if (!$Rows) {Write-Host "No rows with GenerateSecret = TRUE in $ExcelPath (sheet '$WorksheetName') - Aborting Script" -ForegroundColor Red ; exit}

# One line per row in the result CSV, appended at once so an aborted run keeps the folder IDs created so far
function Add-Result ([string]$JobNr, [string]$FolderName, $FolderId, [string]$Status, [string]$Message) {
    [pscustomobject]@{ JobNr = $JobNr; FolderName = $FolderName; FolderId = $FolderId; Status = $Status; Message = $Message } |
        Export-Csv -Path $ResultPath -Delimiter ';' -Encoding UTF8 -NoTypeInformation -Append
}

# $true if the password follows the rules above
function Test-GeneratedPassword ([string]$Password) {
    if ($Password.Length -ne $PasswordLength) { return $false }
    $Upper = $false; $Lower = $false; $Digit = $false; $Special = $false
    foreach ($Char in $Password.ToCharArray()) {
        if ($Char -cmatch '[A-Z]') { $Upper = $true }
        elseif ($Char -cmatch '[a-z]') { $Lower = $true }
        elseif ($Char -match '[0-9]') { $Digit = $true }
        elseif ($PasswordSpecialChars.IndexOf($Char) -ge 0) { $Special = $true }
        else { return $false }
    }
    return ($Upper -and $Lower -and $Digit -and $Special)
}

$PasswordRulesText = "$PasswordLength characters, upper and lower case letter, digit, special character ($PasswordSpecialChars), nothing else"

# One test password per template before anything is created: stops if a template's password requirement doesn't match
foreach ($Definition in $SecretDefinitions) {
    $SecretStub = Invoke-RestMethod -UseDefaultCredentials -ContentType 'application/json' -Method Get -Uri "$SecretServerApi/secrets/stub?filter.secretTemplateId=$($Definition.TemplateId)&filter.folderId=$($SecretServerFolder)"
    $PasswordItem = $SecretStub.items | Where-Object { $_.isPassword }
    if (!(Test-GeneratedPassword (Invoke-RestMethod -UseDefaultCredentials -Method Post -Uri "$SecretServerApi/secret-templates/generate-password/$($PasswordItem.fieldId)"))) {
        Write-Host "Template $($Definition.TemplateId) ($($Definition.Username)): secretserver generates passwords that don't meet the rules ($PasswordRulesText) - check the password requirement of the template - Aborting Script" -ForegroundColor Red ; exit
    }
}

# Subfolders that already exist in the target folder (name -> folder ID)
$ExistingFolders = @{}
foreach ($ExistingFolder in (Invoke-RestMethod -UseDefaultCredentials -Method Get -Uri "$SecretServerApi/folders?filter.parentFolderId=$($SecretServerFolder)&take=1000").records) {
    $ExistingFolders[$ExistingFolder.folderName] = $ExistingFolder.id
}


foreach ($Row in $Rows) {
    $JobNr = "$($Row.JobNr)"
    $FolderName = "$($Row.FolderName)".Trim()
    if (!$FolderName) {
        Write-Host "JobNr ${JobNr}: GenerateSecret is TRUE but FolderName is empty - skipped" -ForegroundColor Yellow
        Add-Result $JobNr '' $null 'NoFolderName' ''
        continue
    }

    if ($ExistingFolders.ContainsKey($FolderName)) {
        Write-Host "Folder '$FolderName' already exists (ID $($ExistingFolders[$FolderName])) - skipped" -ForegroundColor Yellow
        Add-Result $JobNr $FolderName $ExistingFolders[$FolderName] 'Exists' ''
        continue
    }

    # Another subfolder with the same job number in its name; no FolderId in the result, so netbox isn't updated
    if ($JobNr -notmatch '^\d{6}$') {
        Write-Host "Folder '$FolderName': JobNr '$JobNr' is not a 6-digit number - skipped" -ForegroundColor Yellow
        Add-Result $JobNr $FolderName $null 'InvalidJobNr' ''
        continue
    }
    $SameJobNr = @($ExistingFolders.Keys | Where-Object { $_ -match "(?<!\d)$JobNr(?!\d)" })
    if ($SameJobNr.Count -gt 0) {
        $Others = ($SameJobNr | ForEach-Object { "'$_' (ID $($ExistingFolders[$_]))" }) -join ', '
        Write-Host "Folder '$FolderName' not created: JobNr $JobNr is already in subfolder $Others - skipped" -ForegroundColor Yellow
        Add-Result $JobNr $FolderName $null 'JobNrInUse' "JobNr already in subfolder $Others"
        continue
    }

    $Folder = $null
    try {
        # Create subfolder, inheriting permissions and secret policy like the existing location folders
        $FolderStub = Invoke-RestMethod -UseDefaultCredentials -ContentType 'application/json' -Method Get -Uri "$SecretServerApi/folders/stub"

        $FolderStub.folderName = $FolderName
        $FolderStub.parentFolderId = $SecretServerFolder
        $FolderStub.inheritPermissions = $true
        $FolderStub.inheritSecretPolicy = $true
        $FolderStub.secretPolicyId = -1

        $body = $FolderStub | ConvertTo-Json -Depth 10

        $Folder = Invoke-RestMethod -UseDefaultCredentials -ContentType 'application/json' -Method Post -Body ([Text.Encoding]::UTF8.GetBytes($body)) -Uri "$SecretServerApi/folders"
        $ExistingFolders[$FolderName] = $Folder.id
        Write-Host "Folder '$FolderName' created (ID $($Folder.id))" -ForegroundColor Green

        # Create one secret per template in the new subfolder
        foreach ($Definition in $SecretDefinitions) {
            $SecretStub = Invoke-RestMethod -UseDefaultCredentials -ContentType 'application/json' -Method Get -Uri "$SecretServerApi/secrets/stub?filter.secretTemplateId=$($Definition.TemplateId)&filter.folderId=$($Folder.id)"

            $SecretStub.name = $Definition.Username
            $SecretStub.siteId = 1

            ($SecretStub.items | Where-Object { $_.slug -eq 'username' }).itemValue = $Definition.Username

            $PasswordItem = $SecretStub.items | Where-Object { $_.isPassword }
            $PasswordItem.itemValue = Invoke-RestMethod -UseDefaultCredentials -Method Post -Uri "$SecretServerApi/secret-templates/generate-password/$($PasswordItem.fieldId)"
            if (!(Test-GeneratedPassword $PasswordItem.itemValue)) { throw "Generated password for '$($Definition.Username)' doesn't meet the rules ($PasswordRulesText) - secret not created" }

            $body = $SecretStub | ConvertTo-Json -Depth 10

            $Secret = Invoke-RestMethod -UseDefaultCredentials -ContentType 'application/json' -Method Post -Body ([Text.Encoding]::UTF8.GetBytes($body)) -Uri "$SecretServerApi/secrets"
            Write-Host "  Secret '$($Definition.Username)' created (ID $($Secret.id))"
        }
        Add-Result $JobNr $FolderName $Folder.id 'Created' ''
    }
    catch {
        $Message = "$($_.Exception.Message) $($_.ErrorDetails.Message)"
        Write-Host "Error in folder '$FolderName': $Message" -ForegroundColor Red
        # A folder that was created before the error keeps its ID in the result
        if ($Folder) { Add-Result $JobNr $FolderName $Folder.id 'SecretError' $Message }
        else { Add-Result $JobNr $FolderName $null 'FolderError' $Message }
    }
}

Write-Host "Result written to $ResultPath"

