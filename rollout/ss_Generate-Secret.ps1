<#
.SYNOPSIS
    Powershell Script to bulk create location folders with BiRS Windows account secrets in secretserver
.DESCRIPTION
    Reads the sheet 'rollout' of rollout_CredentialRotation.xlsx and creates one subfolder per row with
    GenerateSecret = TRUE in folder 1340 (\Customer\Freie\_Locations), named after column 'FolderName'
    ("<Ortschaft>.<Jobnummer>"). In every new subfolder one secret per template is created.
    Passwords are generated by secretserver according to the password requirement of the template.
    Folders that already exist and rows without FolderName are skipped with a warning.
    Requires the PowerShell module ImportExcel (Excel itself is not needed).
#>

[string]$SecretServerUrl = 'https://secretserver.lag.wan/SecretServer'
$SecretServerApi = "$SecretServerUrl/winauthwebservices/api/v1"
[int]$SecretServerFolder = 1340
[string]$ExcelPath = "$PSScriptRoot\rollout_CredentialRotation.xlsx"
[string]$WorksheetName = 'rollout'

# Username (also used as secret name) and secret template per secret
$SecretDefinitions = @(
    @{ Username = 'BiCA Admin';  TemplateId = 6084 }   # Windows Account (BiRS - BiCA Admin)
    @{ Username = 'BiCA Remote'; TemplateId = 6085 }   # Windows Account (BiRS - BiCA Remote)
    @{ Username = 'PUB-User';    TemplateId = 6087 }   # Windows Account (BiRS - PUB-User)
    @{ Username = 'WinAutoUser'; TemplateId = 7121 }   # Windows Account (BiRS - WinAutoUser)
)

if (!(Get-Module -ListAvailable -Name ImportExcel)) {Write-Host "PowerShell module ImportExcel not installed (Install-Module ImportExcel) - Aborting Script" -ForegroundColor Red ; exit}
if (!(Test-Path -Path $ExcelPath)) {Write-Host "Excel not found: $ExcelPath - Aborting Script" -ForegroundColor Red ; exit}

$Rows = @(Import-Excel -Path $ExcelPath -WorksheetName $WorksheetName | Where-Object { $_.GenerateSecret -eq $true })

if (!$Rows) {Write-Host "No rows with GenerateSecret = TRUE in $ExcelPath (sheet '$WorksheetName') - Aborting Script" -ForegroundColor Red ; exit}

# Subfolders that already exist in the target folder
$ExistingFolders = @((Invoke-RestMethod -UseDefaultCredentials -Method Get -Uri "$SecretServerApi/folders?filter.parentFolderId=$($SecretServerFolder)&take=1000").records.folderName)


foreach ($Row in $Rows) {
    $FolderName = "$($Row.FolderName)".Trim()
    if (!$FolderName) {
        Write-Host "JobNr $($Row.JobNr): GenerateSecret is TRUE but FolderName is empty - skipped" -ForegroundColor Yellow
        continue
    }

    if ($ExistingFolders -contains $FolderName) {
        Write-Host "Folder '$FolderName' already exists - skipped" -ForegroundColor Yellow
        continue
    }

    try {
        # Create subfolder, inheriting permissions and secret policy like the existing location folders
        $FolderStub = Invoke-RestMethod -UseDefaultCredentials -ContentType 'application/json' -Method Get -Uri "$SecretServerApi/folders/stub"

        $FolderStub.folderName = $FolderName
        $FolderStub.parentFolderId = $SecretServerFolder
        $FolderStub.inheritPermissions = $true
        $FolderStub.inheritSecretPolicy = $true
        $FolderStub.secretPolicyId = -1

        $body = $FolderStub | ConvertTo-Json -Depth 10

        $Folder = Invoke-RestMethod -UseDefaultCredentials -ContentType 'application/json' -Method Post -Body ([Text.Encoding]::UTF8.GetBytes($body)) -Uri "$SecretServerApi/folders"
        $ExistingFolders += $FolderName
        Write-Host "Folder '$FolderName' created (ID $($Folder.id))" -ForegroundColor Green

        # Create one secret per template in the new subfolder
        foreach ($Definition in $SecretDefinitions) {
            $SecretStub = Invoke-RestMethod -UseDefaultCredentials -ContentType 'application/json' -Method Get -Uri "$SecretServerApi/secrets/stub?filter.secretTemplateId=$($Definition.TemplateId)&filter.folderId=$($Folder.id)"

            $SecretStub.name = $Definition.Username
            $SecretStub.siteId = 1

            ($SecretStub.items | Where-Object { $_.slug -eq 'username' }).itemValue = $Definition.Username

            $PasswordItem = $SecretStub.items | Where-Object { $_.isPassword }
            $PasswordItem.itemValue = Invoke-RestMethod -UseDefaultCredentials -Method Post -Uri "$SecretServerApi/secret-templates/generate-password/$($PasswordItem.fieldId)"

            $body = $SecretStub | ConvertTo-Json -Depth 10

            $Secret = Invoke-RestMethod -UseDefaultCredentials -ContentType 'application/json' -Method Post -Body ([Text.Encoding]::UTF8.GetBytes($body)) -Uri "$SecretServerApi/secrets"
            Write-Host "  Secret '$($Definition.Username)' created (ID $($Secret.id))"
        }
    }
    catch {
        Write-Host "Error in folder '$FolderName': $($_.Exception.Message) $($_.ErrorDetails.Message)" -ForegroundColor Red
    }
}
